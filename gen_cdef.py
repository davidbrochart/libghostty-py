#!/usr/bin/env python3
"Generate ghostty/_cdef.py from ghostty's libghostty-vt headers. Re-run on each libghostty-vt release bump and review the diff."
import re,subprocess
from pathlib import Path
from build_lib import ghostty_src

EXCLUDE = {'wasm.h'}  # wasm-only utilities; not part of the native ABI surface

def header_order(inc):
    "All ghostty/vt headers reachable from vt.h, in dependency (include) order."
    seen,out = set(),[]
    def walk(name):
        if name in seen or name.rsplit('/',1)[-1] in EXCLUDE: return
        seen.add(name)
        p = inc/name
        for m in re.findall(r'#include <(ghostty/[\w/]+\.h)>', p.read_text()): walk(m)
        out.append(p)
    walk('ghostty/vt.h')
    return out

def clean(src):
    "One C header's text, reduced to cdef-ready declarations."
    src = re.sub(r'\\\n', ' ', src)  # join line-continued macros so they drop as one line
    src = re.sub(r'#ifdef __cplusplus\nextern "C" \{\n#endif', '', src)
    src = re.sub(r'#ifdef __cplusplus\n\}\n#endif', '', src)
    src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
    src = re.sub(r'//[^\n]*', '', src)
    # CFFI ABI mode needs numeric values for the formatter's new flag macros.
    flags = {}
    def flag(m):
        flags[m[1]] = 1 << int(m[2])
        return f'enum {{ {m[1]} = {flags[m[1]]} }};'
    src = re.sub(r'^#define (GHOSTTY_FORMATTER_EXTRA_\w+) \(1u << (\d+)\)$', flag, src, flags=re.M)
    def extras(m):
        expr = m[2].strip().strip('()')
        if re.fullmatch(r'(?:0x[0-9A-Fa-f]+|[0-9]+)u', expr):
            value = int(expr[:-1], 0)
        else:
            value = 0
            for name in expr.split('|'): value |= flags[name.strip()]
        return f'enum {{ {m[1]} = {value} }};'
    src = re.sub(r'^#define (GHOSTTY_FORMATTER_EXTRAS_\w+) +(.+)$', extras, src, flags=re.M)
    src = re.sub(r'^#define (GHOSTTY_STYLE_FLAG_\w+) \(\(GhosttyStyleFlags\)\(1u << (\d+)\)\)$', flag, src, flags=re.M)
    shift = re.search(r'^#define GHOSTTY_STYLE_UNDERLINE_SHIFT (\d+)$', src, re.M)
    if shift:
        value = int(shift[1])
        src = re.sub(r'^#define GHOSTTY_STYLE_UNDERLINE_SHIFT .+$',
                     f'enum {{ GHOSTTY_STYLE_UNDERLINE_SHIFT = {value} }};', src, flags=re.M)
        mask = re.search(r'^#define GHOSTTY_STYLE_UNDERLINE_MASK +\(\(GhosttyStyleFlags\)\((0x[0-9A-Fa-f]+)u << GHOSTTY_STYLE_UNDERLINE_SHIFT\)\)$', src, re.M)
        if mask:
            src = src.replace(mask[0], f'enum {{ GHOSTTY_STYLE_UNDERLINE_MASK = {int(mask[1], 0) << value} }};')
    src = '\n'.join(l for l in src.splitlines() if not l.lstrip().startswith('#'))
    src = re.sub(r'static inline [^{]*\{[^}]*\}', '', src, flags=re.S)  # header-only helpers: no symbol in the lib
    for macro,repl in [('GHOSTTY_API ',''), ('GHOSTTY_ENUM_TYPED ',''), ('GHOSTTY_ENUM_MAX_VALUE','0x7FFFFFFF')]:
        src = src.replace(macro, repl)
    src = re.sub(r'\n{3,}', '\n\n', src).strip()
    return '\n'.join(line.rstrip() for line in src.splitlines())

def gen():
    src = ghostty_src()
    rev = subprocess.run(['git','-C',str(src),'rev-parse','--short=9','HEAD'], capture_output=True, text=True).stdout.strip()
    parts = [f'/* --- {p.name} --- */\n\n{c}' for p in header_order(src/'include') if (c := clean(p.read_text()))]
    body = '\n\n'.join(parts)
    out = f'"Generated by gen_cdef.py from ghostty {rev}. Do not edit."\n\nCDEF = r\'\'\'\n{body}\n\'\'\'\n'
    dest = Path(__file__).parent/'ghostty'/'_cdef.py'
    dest.write_text(out)
    print(f'Wrote {dest} from ghostty {rev}: {len(body)} chars')

if __name__=='__main__': gen()
